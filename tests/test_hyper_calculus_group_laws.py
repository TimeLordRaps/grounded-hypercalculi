def test_contains_identity_is_true_and_asks_nothing() -> None:
    # Retained public API. It cannot return False, which is why the closure is
    # checked for the identity separately above.
    assert PermutationGroup([]).contains_identity() is True
    assert symmetric(20).contains_identity() is True
