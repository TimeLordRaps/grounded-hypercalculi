"""The group machinery must answer or refuse, and never report a number near a cap.

`order()` returned 1000 for S_7, whose order is 5040, and 1001 for S_8, whose
order is 40320 -- the second being neither the order nor the budget, because the
budget was tested before processing a queue entry that then added several
elements. `orbit()` inherited the same cap and returned half of a 2000-point
orbit. `Permutation` accepted maps that are not bijections.

These tests check the group laws directly rather than trusting the enumeration:
closure under composition, presence of inverses, and that orbits partition the
points. A truncated closure fails all three, which is how a budget that
truncates is caught without knowing the right answer in advance.

The `negative_control` tests reproduce the replaced logic, so the defects stay
legible once the source no longer exhibits them.
"""

from __future__ import annotations

import pytest

from grounded_hypercalculi.hyper_calculus import (
    DerivationOperator,
    Permutation,
    PermutationGroup,
    commutator_bracket,
)

IDENTITY = Permutation({})


def cycle(n: int) -> Permutation:
    """The n-cycle (0 1 2 ... n-1)."""
    return Permutation({i: (i + 1) % n for i in range(n)})


def transposition(a: int, b: int) -> Permutation:
    return Permutation({a: b, b: a})


def symmetric(n: int) -> PermutationGroup:
    """S_n, generated by an n-cycle and a transposition."""
    return PermutationGroup([cycle(n), transposition(0, 1)])


# ============================================================================
# 1. order() is the order, or it is a refusal
# ============================================================================


@pytest.mark.parametrize(
    "n, factorial",
    [(3, 6), (4, 24), (5, 120), (6, 720), (7, 5040)],
)
def test_the_order_of_a_symmetric_group_is_n_factorial(n: int, factorial: int) -> None:
    assert symmetric(n).order() == factorial


def test_the_order_of_a_cyclic_group_is_its_length() -> None:
    # 1200 elements, past the old cap of 1000, and previously reported as 1000.
    # Kept at 1200 rather than larger because composing two permutations rebuilds
    # and rehashes a dict the size of their support, so enumerating C_n costs
    # O(n^2) -- C_2000 takes 2.4s where C_1200 takes 0.5s.
    assert PermutationGroup([cycle(1200)]).order() == 1200


def test_a_group_past_the_budget_is_refused_not_approximated() -> None:
    # S_8 has 40320 elements. The old code answered 1001.
    with pytest.raises(ValueError, match="more than 10000 elements"):
        symmetric(8).order()


def test_the_budget_can_be_raised_to_get_the_true_order() -> None:
    assert len(symmetric(8).generate(max_elements=50_000)) == 40_320


def test_a_budget_below_one_is_refused() -> None:
    with pytest.raises(ValueError, match="at least 1"):
        symmetric(3).generate(max_elements=0)


def test_negative_control_the_truncating_loop_returns_neither_order_nor_cap() -> None:
    # The replaced loop, reproduced exactly. It tested the budget once per queue
    # entry rather than once per insertion, so it overshot.
    def legacy_generate(generators, max_elements=1000):
        elements = {IDENTITY}
        queue = [IDENTITY]
        while queue and len(elements) < max_elements:
            curr = queue.pop(0)
            for g in generators:
                comp = curr * g
                if comp not in elements:
                    elements.add(comp)
                    queue.append(comp)
        return elements

    s7 = legacy_generate([cycle(7), transposition(0, 1)])
    s8 = legacy_generate([cycle(8), transposition(0, 1)])
    assert len(s7) == 1000, "S_7 has 5040 elements"
    assert len(s8) == 1001, "S_8 has 40320 elements, and 1001 is not even the cap"


# ============================================================================
# 2. What comes back is a group
# ============================================================================


def test_the_closure_is_closed_under_composition() -> None:
    elements = symmetric(5).generate()
    assert all(a * b in elements for a in elements for b in elements)


def test_every_element_of_the_closure_has_its_inverse_in_the_closure() -> None:
    elements = symmetric(5).generate()
    assert all(any(a * b == IDENTITY for b in elements) for a in elements)


def test_the_identity_is_in_the_closure() -> None:
    assert IDENTITY in symmetric(5).generate()


def test_negative_control_the_truncated_set_is_not_a_group() -> None:
    # The three properties above are what a partial closure fails, and they are
    # checkable without knowing the true order. That is the point of testing
    # them rather than the count alone.
    def legacy_generate(generators, max_elements=1000):
        elements = {IDENTITY}
        queue = [IDENTITY]
        while queue and len(elements) < max_elements:
            curr = queue.pop(0)
            for g in generators:
                comp = curr * g
                if comp not in elements:
                    elements.add(comp)
                    queue.append(comp)
        return elements

    truncated = legacy_generate([cycle(7), transposition(0, 1)])
    sample = sorted(truncated, key=lambda p: sorted(p.mapping.items()))[:40]

    unclosed = [(a, b) for a in sample for b in sample if a * b not in truncated]
    assert unclosed, "the truncated set was not closed under composition"

    without_inverse = [
        a for a in sample if not any(a * b == IDENTITY for b in truncated)
    ]
    assert without_inverse, "members of the truncated set had no inverse present"


