def test_the_orbit_of_a_point_under_a_cycle_is_every_point_of_the_cycle() -> None:
    assert PermutationGroup([cycle(7)]).orbit(0) == set(range(7))


def test_a_long_orbit_is_not_truncated_by_the_group_budget() -> None:
    # 2000 points; previously 1000 of them came back, silently.
    assert PermutationGroup([cycle(2000)]).orbit(0) == set(range(2000))


def test_an_orbit_is_available_for_a_group_far_too_large_to_enumerate() -> None:
    # S_20 has 20! elements -- about 2.4e18, which will not be enumerated under
    # any budget. Its orbit of 0 has twenty points and costs nothing. Computing
    # the orbit through the closure threw that gap away.
    group = symmetric(20)
    assert group.orbit(0) == set(range(20))
    with pytest.raises(ValueError):
        group.order()


def test_orbits_partition_the_points() -> None:
    # Distinct orbits are disjoint and cover everything. The non-bijection
    # Permutation used to accept produced overlapping orbits that were not equal.
    group = symmetric(5)
    points = range(8)
    orbits = {frozenset(group.orbit(x)) for x in points}
    assert sorted(sorted(o) for o in orbits) == [[0, 1, 2, 3, 4], [5], [6], [7]]
    for a in orbits:
        for b in orbits:
            assert a == b or not (a & b)


def test_a_point_is_always_in_its_own_orbit() -> None:
    assert 99 in PermutationGroup([cycle(5)]).orbit(99)
    assert PermutationGroup([]).orbit(3) == {3}


# ============================================================================
# 4. A Permutation must permute
# ============================================================================


def test_a_non_injective_map_is_refused() -> None:
    # 1 and 3 both land on 2, and nothing lands on 1 or 3.
    with pytest.raises(ValueError, match="not injective"):
        Permutation({1: 2, 3: 2})


def test_a_map_that_moves_a_point_without_covering_it_is_refused() -> None:
    # 1 -> 2 alone also sends 2 -> 2, so 2 has two preimages.
    with pytest.raises(ValueError, match="does not permute its own support"):
        Permutation({1: 2})


def test_a_cycle_with_one_entry_too_many_is_refused() -> None:
    with pytest.raises(ValueError, match="not injective"):
        Permutation({0: 1, 1: 2, 2: 0, 3: 0})


def test_genuine_permutations_are_unaffected() -> None:
    assert Permutation({1: 2, 2: 1}).apply(1) == 2
    assert Permutation({1: 1, 2: 2}) == IDENTITY
    assert hash(Permutation({1: 1})) == hash(IDENTITY)
    assert cycle(6).apply(5) == 0


def test_composition_of_permutations_is_a_permutation() -> None:
    # __mul__ builds a new Permutation, so validation runs on every product. If
    # composition could produce a non-bijection this would raise.
    elements = symmetric(5).generate()
    for a in list(elements)[:20]:
        for b in list(elements)[:20]:
            product = a * b
            assert set(product.mapping) == set(product.mapping.values())


def test_negative_control_the_old_canonicalization_accepted_a_non_bijection() -> None:
    # The replaced __post_init__ dropped fixed points and stopped there.
    raw = {1: 2, 3: 2}
    cleaned = {k: v for k, v in raw.items() if k != v}
    assert cleaned == raw, "nothing was dropped, and nothing else was checked"
    images = list(cleaned.values())
    assert len(set(images)) != len(images), "which the check now added catches"


# ============================================================================
# 5. Derivations and the Lie bracket -- this part was already right
# ============================================================================

_H = 1e-5


def _scaled_derivative(coefficient):
    """f -> coefficient(x) * f'(x), a derivation for any smooth coefficient."""
    return lambda f: (lambda x: coefficient(x) * (f(x + _H) - f(x - _H)) / (2 * _H))


D_DX = DerivationOperator("d/dx", _scaled_derivative(lambda x: 1.0))
X_D_DX = DerivationOperator("x d/dx", _scaled_derivative(lambda x: x))


def _f(x: float) -> float:
    return x ** 2 + 1.0


def _g(x: float) -> float:
    return 3.0 * x + 2.0


def test_the_generators_satisfy_leibniz() -> None:
    assert D_DX.leibniz_check(_f, _g, 1.3) is True
    assert X_D_DX.leibniz_check(_f, _g, 1.3) is True


def test_the_bracket_of_two_derivations_is_itself_a_derivation() -> None:
    # The Lie algebra fact: derivations are closed under the commutator, even
    # though general linear operators are not.
    bracket = commutator_bracket(D_DX, X_D_DX)
    assert bracket.leibniz_check(_f, _g, 1.3) is True


def test_the_bracket_is_antisymmetric() -> None:
    forward = commutator_bracket(D_DX, X_D_DX).apply(_f)(1.3)
    reversed_ = commutator_bracket(X_D_DX, D_DX).apply(_f)(1.3)
    assert forward == pytest.approx(-reversed_, abs=1e-9)


def test_the_bracket_of_an_operator_with_itself_vanishes() -> None:
    assert commutator_bracket(D_DX, D_DX).apply(_f)(1.3) == pytest.approx(0.0, abs=1e-9)


def test_leibniz_check_says_no_when_the_rule_fails() -> None:
    # Squaring is not a derivation: D(fg) = (fg)^2, not f^2 g + f g^2.
    squaring = DerivationOperator("f -> f^2", lambda f: (lambda x: f(x) ** 2))
    assert squaring.leibniz_check(_f, _g, 1.3) is False


def test_the_identity_operator_is_not_a_derivation() -> None:
    # D(fg) = fg, but D(f)g + fD(g) = 2fg. Equal only where fg is zero.
    identity_op = DerivationOperator("f -> f", lambda f: f)
    assert identity_op.leibniz_check(_f, _g, 1.3) is False


